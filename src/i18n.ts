const TABLES: Record<Locale, Dict> = {
  en,
  es,
  fr,
  de,
  'pt-BR': ptBR,
  it,
  ru,
  'zh-CN': zhCN,
  ja,
};

// ---------------------------------------------------------------------------
// Runtime
// ---------------------------------------------------------------------------

function detectInitialLocale(): Locale {
  try {
    const stored = window.localStorage?.getItem(STORAGE_KEY);
    if (stored && (LOCALES as readonly string[]).includes(stored)) return stored as Locale;
  } catch {
    // localStorage unavailable — fall through to navigator detection.
  }
  const candidates = typeof navigator !== 'undefined'
    ? [navigator.language, ...(navigator.languages ?? [])]
    : [];
  for (const raw of candidates) {
    if (!raw) continue;
    const lower = raw.toLowerCase();
    if (lower === 'pt-br' || lower.startsWith('pt-br')) return 'pt-BR';
    if (lower.startsWith('pt')) return 'pt-BR';
    if (lower === 'zh-cn' || lower.startsWith('zh-hans') || lower.startsWith('zh')) return 'zh-CN';
    const base = lower.split('-')[0];
    if ((LOCALES as readonly string[]).includes(base)) return base as Locale;
  }
  return 'en';
}

let current: Locale = detectInitialLocale();

export function getLocale(): Locale {
  return current;
}

export function setLocale(locale: Locale): void {
  if (!(LOCALES as readonly string[]).includes(locale)) return;
  current = locale;
  try {
    window.localStorage?.setItem(STORAGE_KEY, locale);
  } catch {
    // Ignore write failures (private browsing).
  }
}

/** Cycle to the next/previous locale in {@link LOCALES}; returns the new one. */
export function cycleLocale(dir: 1 | -1 = 1): Locale {
  const i = LOCALES.indexOf(current);
  const next = LOCALES[(i + dir + LOCALES.length) % LOCALES.length];
  setLocale(next);
  return next;
}

/**
 * Translate `key`, substituting `{name}` placeholders from `params`.
 * Falls back: current locale → English → the key itself.
 */
export function t(key: string, params?: Record<string, string | number>): string {
  let str = TABLES[current]?.[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

/**
 * A canvas font-family stack that keeps the game's display face for Latin text
 * but falls back to widely-installed system faces so Cyrillic, Japanese and
 * Chinese glyphs still render (the bundled Poiret One / BJ Cree fonts are
 * Latin-only). Pass the base family the caller would otherwise use.
 */
export function localizedFontStack(base: string): string {
  return `${base}, "Noto Sans", "Noto Sans CJK SC", "Noto Sans CJK JP", "Microsoft YaHei", "PingFang SC", "Hiragino Kaku Gothic ProN", "Yu Gothic", "Meiryo", "Segoe UI", sans-serif`;
}

/** True when the active locale needs the non-Latin fallback fonts. */
export function localeNeedsFallbackFont(): boolean {
  return current === 'ru' || current === 'ja' || current === 'zh-CN';
}
